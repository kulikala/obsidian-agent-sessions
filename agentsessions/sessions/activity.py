"""Activity spans: when an agent was actually working in a session.

A *turn* runs from the moment a prompt reaches the agent (a typed prompt, or a notification
that wakes it, e.g. a finished background task) to the last thing the agent recorded before the
next prompt. Consecutive turns whose gap (end of one to the start of the next) is shorter than
the gap setting are joined into one block, so a run of related work reads as one flow. This
module holds the pure turn/span arithmetic, the cache of per-transcript turns, and the Claude
Code transcript reader; the Codex and OpenCode readers live next to their own parsing
(`agents/codex/rollout.py`, `agents/opencode/scan.py`).
"""

import json
import os
import re
from datetime import datetime, timezone
from typing import Dict, List, Optional

DEFAULT_GAP_SECONDS = 30 * 60
MIN_SPAN_SECONDS = 60.0
# A last turn whose final record is this recent is taken to still be running: it ends "now".
LIVE_WINDOW_SECONDS = 120.0
# Bumped whenever how turns are read changes: a cached entry of another version is recomputed.
ACTIVITY_VERSION = 1

_TS_RE = re.compile(rb'"timestamp":"(\d{4}-\d\d-\d\dT\d\d:\d\d:\d\d(?:\.\d+)?)Z"')
# Claude Code user lines that carry text but aren't a prompt reaching the agent.
_NOT_A_TURN_PREFIXES = (
    '<local-command-stdout>',
    '<local-command-caveat>',
    'Caveat: The messages below were generated by the user',
    '[Request interrupted',
    'This session is being continued from a previous conversation',
)


class TurnBuilder:
    """Feeds on `(time, is_prompt)` events in transcript order and yields `[start, end]` turns."""

    def __init__(self) -> None:
        self.turns: List[List[float]] = []
        self._current: Optional[List[float]] = None
        self._pre: Optional[List[float]] = None   # activity before the first prompt

    def prompt(self, t: float) -> None:
        self._current = [t, t]
        self.turns.append(self._current)

    def activity(self, t: float) -> None:
        if self._current is not None:
            if t > self._current[1]:
                self._current[1] = t
        elif self._pre is None:
            self._pre = [t, t]
        elif t > self._pre[1]:
            self._pre[1] = t
        elif t < self._pre[0]:
            self._pre[0] = t

    def finish(self) -> List[List[float]]:
        """Activity that precedes every prompt only counts when there is no prompt at all."""
        if not self.turns and self._pre is not None:
            return [self._pre]
        return self.turns


def join_turns(turns: List[List[float]], gap: float = DEFAULT_GAP_SECONDS,
               min_len: float = MIN_SPAN_SECONDS) -> List[List[float]]:
    """`[[start, end], ...]` blocks: turns (any order) are joined when the next one starts less
    than `gap` after the previous block's end; a block shorter than `min_len` is extended to
    `min_len` so a one-message turn stays visible."""
    blocks: List[List[float]] = []
    for start, end in sorted(([a, b] for a, b in turns), key=lambda x: x[0]):
        if blocks and start - blocks[-1][1] < gap:
            blocks[-1][1] = max(blocks[-1][1], end)
        else:
            blocks.append([start, end])
    for b in blocks:
        if b[1] - b[0] < min_len:
            b[1] = b[0] + min_len
    return blocks


def extend_if_live(turns: List[List[float]], now: float,
                   window: float = LIVE_WINDOW_SECONDS) -> List[List[float]]:
    """The turn that is still running (its last record is within `window` of `now`) ends now."""
    if not turns:
        return turns
    last = max(range(len(turns)), key=lambda i: turns[i][1])
    if 0 <= now - turns[last][1] < window:
        turns = [list(t) for t in turns]
        turns[last][1] = now
    return turns


def clip_spans(spans: List[List[float]], start: float, end: float) -> List[List[float]]:
    """The parts of `spans` inside `[start, end)`; empty ones are dropped."""
    out = []
    for a, b in spans:
        a, b = max(a, start), min(b, end)
        if b > a:
            out.append([a, b])
    return out


def parse_utc(value: str) -> Optional[float]:
    fmt = '%Y-%m-%dT%H:%M:%S.%f' if '.' in value else '%Y-%m-%dT%H:%M:%S'
    try:
        return datetime.strptime(value, fmt).replace(tzinfo=timezone.utc).timestamp()
    except ValueError:
        return None


def _starts_turn(rec: dict) -> bool:
    """A user line that is a prompt reaching the agent: typed text, or an injected
    notification (a finished background task, another session's message). Not tool results,
    meta lines, sub-agent lines, or command output."""
    if rec.get('isMeta') or rec.get('isSidechain'):
        return False
    content = (rec.get('message') or {}).get('content')
    if isinstance(content, str):
        text = content
    elif isinstance(content, list):
        text = '\n'.join(b.get('text', '') for b in content
                         if isinstance(b, dict) and b.get('type') == 'text' and b.get('text'))
    else:
        return False
    text = text.lstrip()
    return bool(text) and not text.startswith(_NOT_A_TURN_PREFIXES)


def claude_turns(path: str) -> List[List[float]]:
    """Turns of a Claude Code transcript. Every user and assistant line is activity (tool
    results and sub-agent work included: the agent was working); a line that `_starts_turn`
    also starts a turn."""
    b = TurnBuilder()
    try:
        f = open(path, 'rb')
    except OSError:
        return []
    with f:
        for line in f:
            if b'"timestamp"' not in line:
                continue
            is_user = b'"type":"user"' in line
            if not is_user and b'"type":"assistant"' not in line:
                continue
            m = _TS_RE.search(line)
            t = parse_utc(m.group(1).decode()) if m else None
            if t is None:
                continue
            # Only user lines that carry text can start a turn; tool-result lines are the bulk
            # of a transcript and are never parsed.
            if is_user and (b'"type":"text"' in line or b'"content":"' in line):
                try:
                    rec = json.loads(line)
                except ValueError:
                    rec = None
                if isinstance(rec, dict) and _starts_turn(rec):
                    b.prompt(t)
                    continue
            b.activity(t)
    return b.finish()


def load_cache(path: str) -> Dict[str, dict]:
    from . import cache
    return cache.load(path=path)


def save_cache(c: Dict[str, dict], path: str) -> None:
    from . import cache
    cache.save(c, path=path)


def cached_turns(c: Dict[str, dict], key: str, size: int, mtime: float, compute,
                 trust: bool = True) -> List[List[float]]:
    """The turns for `key` from cache `c` when its (size, mtime, version) still match, else
    `compute()`d and stored. `trust=False` (a file written within the last moments, whose mtime
    can't tell two writes apart) always recomputes."""
    entry = c.get(key)
    if (trust and isinstance(entry, dict) and entry.get('version') == ACTIVITY_VERSION
            and entry.get('size') == size and entry.get('mtime') == mtime):
        return entry.get('turns') or []
    turns = compute()
    c[key] = {'version': ACTIVITY_VERSION, 'size': size, 'mtime': mtime, 'turns': turns}
    return turns
