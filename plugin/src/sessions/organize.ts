// "Organize names and categories": the pure parts — which sessions to propose names for, the
// evidence and prompts sent to a headless agent, the parsing of what comes back and the rules a
// name and a category must meet (checked, asked again once, then enforced). Which agent and
// its argv are in `organize-agent.ts`, the process spawning in `backend/headless.ts`, the dialog
// in `ui/organize-modal.ts`.
// Kept free of any `obsidian` import so tests can import it directly.

import type { Row } from "./index";
import { composeName } from "./name";
import { splitName } from "./tree";

/** How many sessions one run proposes names for. */
export const ORGANIZE_BATCH_CAP = 30;

/** Per-field excerpt limits (characters), so a batch stays a small prompt. */
const FOLDER_MAX = 80;
const FIRST_PROMPT_MAX = 300;
const RECENT_PROMPT_MAX = 240;
const RECENT_PROMPT_COUNT = 3;
const ASSISTANT_MAX = 300;
const REASON_MAX = 100;
const COMMENT_MAX = 300;
/** How many existing categories the prompt lists, and how many example names each carries. */
const CATEGORY_LIST_CAP = 40;
const EXAMPLES_PER_CATEGORY = 3;
const EXAMPLE_MAX = 40;

/** A name is at most this long: CJK text counts characters, other text counts words and characters. */
export const NAME_LIMIT = { cjkChars: 20, words: 5, latinChars: 32 } as const;
/** A category is shorter still. */
export const CATEGORY_LIMIT = { cjkChars: 12, words: 3, latinChars: 24 } as const;

export interface OrganizeCandidate {
	id: string;
	agent: string;
	/** The session's current full name (`Category: Name`), if it has one. */
	name: string | null;
	/** The session's folder, vault-relative when it is inside the vault: a hint at the project. */
	folder: string;
	/** The first prompt (`Row.label`). */
	firstPrompt: string;
	/** The last few prompts a human typed, oldest first. */
	recentPrompts: string[];
	lastAssistant: string;
}

export interface Suggestion {
	id: string;
	category: string;
	name: string;
	/** One line on why this category and name; empty when the model gave none. */
	reason: string;
	/** The model kept the session's current category and name. */
	keep: boolean;
}

/** A session to propose again: the suggestion the user did not accept and what they said about it. */
export interface Revision {
	id: string;
	previous: { category: string; name: string };
	comment: string;
}

/** An existing category with how many sessions use it and a few of their names. */
export interface CategoryProfile {
	category: string;
	sessions: number;
	examples: string[];
}

/** Whether `name` lacks a name or a category — what "only unnamed / uncategorized" selects. */
export function isIncomplete(name: string | null): boolean {
	return !name || splitName(name)[0] === null;
}

/**
 * The sessions a run covers: not archived, not a headless child, newest first, at most `cap`.
 * With `onlyIncomplete`, sessions that already have both a name and a category are left out;
 * either way the incomplete ones come before the complete ones.
 */
export function selectSessions(
	rows: Row[],
	opts: { onlyIncomplete: boolean; cap?: number }
): Row[] {
	const cap = opts.cap ?? ORGANIZE_BATCH_CAP;
	const live = rows.filter((r) => !r.archived && !r.child);
	const pool = opts.onlyIncomplete ? live.filter((r) => isIncomplete(r.name)) : live;
	const byRecent = (a: Row, b: Row): number => b.last_activity - a.last_activity;
	const incomplete = pool.filter((r) => isIncomplete(r.name)).sort(byRecent);
	const complete = pool.filter((r) => !isIncomplete(r.name)).sort(byRecent);
	return [...incomplete, ...complete].slice(0, cap);
}

/** Collapses whitespace and cuts to `max` characters (with an ellipsis). */
export function excerpt(text: string | null | undefined, max: number): string {
	const flat = (text ?? "").replace(/\s+/g, " ").trim();
	return flat.length > max ? `${flat.slice(0, max - 1)}…` : flat;
}

// ---- Evidence per session ---------------------------------------------------------

/** Openings of user lines nobody typed (the program filters these too; this guards older output). */
const NOT_HUMAN_PREFIXES = [
	"Another Claude session sent a message:",
	"This session is being continued from a previous conversation",
	"The user has opened the note",
	"Caveat: The messages below were generated by the user",
	"[Request interrupted",
	"Monitor event:",
];
const INJECTED_TAG = /<(?:system-reminder|task-notification|teammate-message|local-command-[a-z]+|command-name)\b/i;

/** Whether `text` is something a person typed, not a notification, teammate message, task
 * notification, system reminder or command echo that was injected into the conversation. */
export function isHumanPrompt(text: string): boolean {
	const head = text.trimStart();
	if (!head || head.startsWith("<")) {
		return false;
	}
	return !NOT_HUMAN_PREFIXES.some((prefix) => head.startsWith(prefix)) && !INJECTED_TAG.test(head);
}

/** The last few human prompts of a session, oldest first, each cut short and without repeats. */
function recentPrompts(detail: { last_user: string | null; recent_user?: string[] } | null): string[] {
	const list = detail?.recent_user?.length ? detail.recent_user : detail?.last_user ? [detail.last_user] : [];
	const out: string[] = [];
	for (const prompt of list) {
		const cut = isHumanPrompt(prompt) ? excerpt(prompt, RECENT_PROMPT_MAX) : "";
		if (cut && cut !== out[out.length - 1]) {
			out.push(cut);
		}
	}
	return out.slice(-RECENT_PROMPT_COUNT);
}

/** The folder as a hint at the project: vault-relative inside the vault, else its own name. */
export function folderHint(cwd: string, folder: string, vaultPath?: string): string {
	const norm = (path: string): string => path.replace(/\\/g, "/").replace(/\/+$/, "");
	const dir = norm(cwd);
	const vault = vaultPath ? norm(vaultPath) : "";
	if (dir && vault) {
		if (dir === vault) {
			return "(vault root)";
		}
		if (dir.startsWith(`${vault}/`)) {
			return excerpt(dir.slice(vault.length + 1), FOLDER_MAX);
		}
	}
	return excerpt(folder, FOLDER_MAX);
}

export function toCandidate(
	row: Pick<Row, "id" | "agent" | "name" | "label" | "folder" | "cwd">,
	detail: { last_user: string | null; last_assistant: string | null; recent_user?: string[] } | null,
	vaultPath?: string
): OrganizeCandidate {
	const label = row.label ?? "";
	const first = label === row.id || !isHumanPrompt(label) ? "" : label;
	return {
		id: row.id,
		agent: row.agent,
		name: row.name,
		folder: folderHint(row.cwd, row.folder, vaultPath),
		firstPrompt: excerpt(first, FIRST_PROMPT_MAX),
		recentPrompts: recentPrompts(detail),
		lastAssistant: excerpt(detail?.last_assistant, ASSISTANT_MAX),
	};
}

/** Masks texts as the efficiency digest does (`agent-sessions json mask`), each cut to at most
 * `limit` characters. Rejects rather than return them unmasked. */
export type MaskTexts = (texts: string[], limit: number) => Promise<string[]>;

/** The longest excerpt of a candidate: what `MaskTexts` keeps of each text. */
const MASK_LIMIT = Math.max(FIRST_PROMPT_MAX, RECENT_PROMPT_MAX, ASSISTANT_MAX, FOLDER_MAX);

export type CandidateDetail = { last_user: string | null; last_assistant: string | null; recent_user?: string[] };

/**
 * `toCandidate` for each row with what comes from the conversation (the first prompt, the latest
 * prompts, the last reply, the folder) masked by `mask` in one call, before it is cut: what the
 * headless agent sees is masked as the efficiency digest is.
 */
export async function maskedCandidates(
	rows: Pick<Row, "id" | "agent" | "name" | "label" | "folder" | "cwd">[],
	details: (CandidateDetail | null)[],
	vaultPath: string | undefined,
	mask: MaskTexts
): Promise<OrganizeCandidate[]> {
	const texts: string[] = [];
	const put = (text: string): number => texts.push(text) - 1;
	const slots = rows.map((row, i) => {
		const detail = details[i];
		const label = row.label ?? "";
		const recent = detail?.recent_user?.length ? detail.recent_user : detail?.last_user ? [detail.last_user] : [];
		return {
			first: put(label === row.id || !isHumanPrompt(label) ? "" : label),
			recent: recent.filter(isHumanPrompt).map(put),
			assistant: put(detail?.last_assistant ?? ""),
			folder: put(folderHint(row.cwd, row.folder, vaultPath)),
		};
	});
	const masked = texts.length > 0 ? await mask(texts, MASK_LIMIT) : [];
	if (masked.length !== texts.length) {
		throw new Error("mask: wrong number of texts");
	}
	return rows.map((row, i) => {
		const slot = slots[i];
		const candidate = toCandidate(
			{ ...row, label: masked[slot.first] },
			{ last_user: null, recent_user: slot.recent.map((j) => masked[j]), last_assistant: masked[slot.assistant] },
			vaultPath
		);
		return { ...candidate, folder: excerpt(masked[slot.folder], FOLDER_MAX) };
	});
}

/**
 * The user's existing categories as the model should see them: how many sessions use each and a
 * few of their names, so it can tell what kind of thing each category is (a project, a client, an
 * area). Most used first, at most `CATEGORY_LIST_CAP`.
 */
export function categoryProfiles(rows: Pick<Row, "name" | "last_activity" | "child">[]): CategoryProfile[] {
	const byCategory = new Map<string, { last: number; name: string }[]>();
	for (const row of rows) {
		if (row.child || !row.name) {
			continue;
		}
		const [category, name] = splitName(row.name);
		if (!category) {
			continue;
		}
		const list = byCategory.get(category) ?? [];
		list.push({ last: row.last_activity, name });
		byCategory.set(category, list);
	}
	return [...byCategory.entries()]
		.map(([category, list]) => {
			const recent = list.sort((a, b) => b.last - a.last).map((e) => excerpt(e.name, EXAMPLE_MAX));
			return { category, sessions: list.length, examples: [...new Set(recent)].slice(0, EXAMPLES_PER_CATEGORY) };
		})
		.sort((a, b) => b.sessions - a.sessions || a.category.localeCompare(b.category, "ja"))
		.slice(0, CATEGORY_LIST_CAP);
}

function sessionPayload(candidates: OrganizeCandidate[]): object[] {
	return candidates.map((c) => ({
		id: c.id,
		currentName: c.name ?? "",
		folder: c.folder,
		firstPrompt: c.firstPrompt,
		recentPrompts: c.recentPrompts,
		lastAssistantReply: c.lastAssistant,
	}));
}

